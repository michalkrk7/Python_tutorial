#Fundamental Data Types
# int and float
print(type(2 + 4))
print(type(2 - 4))
print(type(2 * 4)) # int for whole numbers
print(type(2 / 4)) # 0.5 -> float for decimal numbers

#type -> sprawdzanie typu danych

print(2 ** 4) # potęgi
print(5 // 4) # zaokrąglenie w dół z dzielenia
print(2 % 4) # 2 -> int reszta z dzielenia

#math functions 
print(round(3.9)) # zaokrąglenie do najbliższej liczby po przecinku
print(abs(-20)) # wartość bezwzględna

